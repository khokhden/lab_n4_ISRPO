import math

def area(r):
    """
    Вычисляет площадь круга по его радиусу.

    Параметры:
        r (float): радиус круга

    Возвращаемое значение:
        float: площадь круга, вычисленная по формуле S = πr²

    Пример вызова:
        area(1): выведет -> 3.141592653589793
    """
    return math.pi * r * r


def perimeter(r):
    """
    Вычисляет длину окружности по её радиусу.

    Параметры:
        r (float): радиус окружности

    Возвращаемое значение:
        float: длина окружности, вычисленная по формуле P = 2πr

    Пример вызова:
        perimeter(1): выведет -> 6.283185307179586
    """
    return 2 * math.pi * r

