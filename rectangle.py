def area(a, b):
    """
    Вычисляет площадь прямоугольника по длинам двух его смежных сторон.

    Параметры:
        a (float): длина первой стороны
        b (float): длина второй стороны

    Возвращаемое значение:
        float: площадь прямоугольника, вычисленная по формуле S = ab

    Пример вызова:
        area(3, 4): выведет -> 12
    """
    return a * b


def perimeter(a, b):
    """
    Вычисляет периметр прямоугольника по длинам двух его смежных сторон.

    Параметры:
        a (float): длина первой стороны
        b (float): длина второй стороны

    Возвращаемое значение:
        float: периметр прямоугольника, вычисленный по формуле P = 2(a + b)

    Пример вызова:
        perimeter(3, 4): выведет -> 14
    """
    return 2 * (a + b)

