def area(a):
    """
    Вычисляет площадь квадрата по длине его стороны.

    Параметры:
        a (float): длина стороны квадрата

    Возвращаемое значение:
        float: площадь квадрата, вычисленная по формуле S = a²

    Пример вызова:
        area(5): выведет -> 25
    """
    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата по длине его стороны.

    Параметры:
        a (float): длина стороны квадрата

    Возвращаемое значение:
        float: периметр квадрата, вычисленный по формуле P = 4a

    Пример вызова:
        perimeter(5): выведет -> 20
    """
    return 4 * a