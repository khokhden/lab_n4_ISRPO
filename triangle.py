def area(a, h):
    """
    Вычисляет площадь треугольника по длине основания и высоте,
    опущенной на это основание.

    Параметры:
        a (float): длина основания
        h (float): длина высоты, проведённой к основанию

    Возвращаемое значение:
        float: площадь треугольника, вычисленная по формуле S = ah/2

    Пример вызова:
        area(6, 4): выведет -> 12.0
    """
    return a * h / 2


def perimeter(a, b, c):
    """
    Вычисляет периметр треугольника по длинам трёх его сторон.

    Параметры:
        a (float): длина первой стороны
        b (float): длина второй стороны
        c (float): длина третьей стороны

    Возвращаемое значение:
        float: периметр треугольника, вычисленный по формуле P = a + b + c

    Пример вызова:
        perimeter(3, 4, 5): выведет -> 12
    """
    return a + b + c
